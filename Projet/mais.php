<h2>Préparation</h2>
<ol>
    <li>Enlevez les feuilles, les barbes et les tiges des épis de maïs.</li>
    <li>Faites bouillir de l'eau salée dans une grande casserole puis, dès qu'elle bout, plongez-y les épis et laissez cuire pendant 10 à 15 min.</li>
    <li>Égouttez les épis et laissez sécher 5 min.</li>
    <li>Badigeonnez les épis de beurre salé fondu puis faites-les griller au barbecue pendant 10 à 15 min. Retournez-les de temps en temps pour qu'ils ne brûlent pas et arrosez de beurre.</li>
    <li>Servez avec, sur le côté, du beurre, du sel et du poivre.</li>
</ol>

