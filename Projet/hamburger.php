<h2>Préparation</h2>
<ol>
    <li>Dans un saladier, malaxer la viande hachée avec l'œuf, l'oignon, le sel, le poivre et les herbes.</li>
    <li>Former ensuite 4 steaks hachés assez plats.</li>
    <li>Mettre sur le barbecue et retourner jusqu'à la cuisson souhaitée.</li>
    <li>Faire griller le bacon au barbecue.</li>
    <li>Couper les pains à hamburger en 2 et les faire toaster sur le barbecue. Lorsqu'ils sont chauds, mettre une tranche de fromage sur chaque moitié et laisser fondre.</li>
    <li>Quand tout est prêt, former les hamburgers en ajoutant une rondelle de tomate, une rondelle d'oignon, une rondelle de cornichon, une feuille de salade, du ketchup, de la moutarde et une tranche de bacon grillée.</li>
</ol>

<p>Pour plus de plaisir, servez avec des frites !</p>

