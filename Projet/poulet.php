<h2>Préparation</h2>
<ol>
    <li>Sur une planche, découper les blancs de poulet en petits morceaux, et les 2 poivrons et les 2 échalotes en gros dés.</li>
    <li>Les mettre dans un saladier avec l'huile d'olive, la coriandre, le cumin et une cuillère à soupe de miel (garder l'autre pour le badigeonnage). Saler et poivrer à votre convenance.</li>
    <li>Les faire mariner pendant 2h minimum au frais.</li>
    <li>Sur des piques à brochette, alterner blancs de poulet, poivrons et échalotes.</li>
    <li>Les mettre à cuire au barbecue pendant 12-15 minutes en retournant régulièrement, jusqu'à ce que le poulet soit bien cuit.</li>
    <li>Avec le reste de la marinade, rajouter du miel et badigeonner les brochettes de ce mélange pendant la cuisson.</li>
</ol>

